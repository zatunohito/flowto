from dsl import *
from lib import *

META = dict(chip="第2回", title="因数分解② 式の特徴に着目", color="#0d9488", bgm=["focus", "calm"])


def build():
    S = []
    S.append(opening("第2回", "因数分解② 式の特徴に着目", "形を見抜いて、公式に持ち込む",
                     ["式の一部を、ひとかたまりの文字として見られる", "平方の差が「隠れている」式を見抜ける", "$x^4$ のような式も、置き換えで因数分解できる"],
                     "第二回は、式の特徴に着目して、因数分解の公式が使える形を、自分で作る方法です。",
                     ["一つ目。式の一部を、ひとかたまりの文字として、見られるようになります。",
                      "二つ目。平方の差が、隠れている式を、見抜けるようになります。",
                      "三つ目。エックスの四乗のような、次数の高い式も、置き換えで、因数分解できるようになります。"]))

    # ------------------------------------------------------------ idea
    s = Scene("かたまりで見る", "置き換えの考え方")
    s.beat("公式が、そのままでは使えない式に出会ったら、どうすればよいでしょう。コツは、式の一部を、ひとかたまりの文字として、見ることです。", T("式の形の特徴に着目して、変形する", "big c"))
    w = Work(size=56)
    s.beat("たとえば、エックスたすワイの二乗、たす三かけるエックスたすワイ、たす二。見た目は複雑ですが、エックスたすワイを、まとめてエーとおいてみます。", w.row(r"(x+y)^2+3(x+y)+2"))
    s.beat("すると、エーの二乗、たす三エー、たす二。これなら、簡単です。足して三、かけて二になる数は、一と二。", w.row(r"A^2+3A+2", note="←$x+y=A$ とおく"))
    s.beat("エーたす一、かける、エーたす二、と因数分解できます。", w.row(r"(A+1)(A+2)"))
    s.beat("最後に、エーを、エックスたすワイに戻します。エックスたすワイたす一、かける、エックスたすワイたす二。複雑な式も、かたまりで見れば、見通しがよくなります。", w.row(r"(x+y+1)(x+y+2)", ans=True, note="←$A$ を戻す"))
    S.append(s)

    # ------------------------------------------------------------ ex5
    s = Scene("例題5", "$x^2-y^2-2y-1$")
    s.beat("例題五。次の式を、因数分解せよ。エックスの二乗、ひく、ワイの二乗、ひく二ワイ、ひく一。", Prob("例題5", "$x^2-y^2-2y-1$"), voice="K")
    s.beat("まず、式の形を、よく見ます。エックスは、エックスの二乗だけ。残りの、マイナスワイの二乗、マイナス二ワイ、マイナス一は、ワイだけの式です。ここを、ひとまとまりで考えましょう。", Eq(r"x^2\ \bl{-y^2-2y-1}", size=64))
    w = Work(size=54, lw=70)
    s.beat("後ろの三つの項を、マイナスで、くくります。かっこの中は、すべて符号が逆になって、ワイの二乗、たす二ワイ、たす一です。", w.row(r"x^2-y^2-2y-1"), w.row(r"x^2-(y^2+2y+1)", note="←マイナスでくくる"))
    s.beat("かっこの中は、ワイたす一の、二乗です。完全平方式でした。", w.row(r"x^2-(y+1)^2", note="←$y^2+2y+1=(y+1)^2$"))
    s.beat("すると、エックスの二乗、ひく、ワイたす一の二乗。これは、平方の差の形です。ワイたす一を、エーとおくと、エックスの二乗ひくエーの二乗。エックスたすエー、かける、エックスひくエー、です。", w.row(r"\{x+(y+1)\}\{x-(y+1)\}", note="←$y+1=A$ とおくと\n$x^2-A^2=(x+A)(x-A)$"))
    s.beat("エーを、ワイたす一に戻して、かっこをはずします。後ろの、マイナスのかっこは、中の符号が変わって、エックスひくワイひく一。", w.row(r"(x+y+1)(x-y-1)", ans=True))
    bx = Box("warn", T("$-(y+1)$ のかっこをはずすと、$-y-1$。[[r:符号の変え忘れ]]に注意。"), T("検算：$(x+y+1)(x-y-1)=x^2-(y+1)^2=x^2-y^2-2y-1$ ✔"))
    s.beat("よくある間違いは、このマイナスのかっこの、符号の変え忘れです。検算すると、エックスの二乗ひく、ワイたす一の二乗となり、元の式に戻ります。", bx)
    S.append(s)

    s = Scene("ポイント：平方の差を作る", "X²−Y² の形を探す")
    bx = Box("point", T("式を変形して、[[o:平方の差 $X^2-Y^2$]] の形を作る。"), T("→ 公式　$X^2-Y^2=(X+Y)(X-Y)$ が使える。"))
    bx2 = Box("tip", T("探し方①　[[b:平方（二乗）になっている部分]]を探す。"), T("探し方②　3項が[[b:完全平方式]]の形になっていないか調べる。"), T("探し方③　[[r:マイナスでくくる]]と、完全平方式が現れることがある。"), title="探し方")
    s.beat("このように、式を変形して、平方の差の形を作ると、因数分解の公式が使えます。", bx)
    s.beat("探し方は三つ。一つ目、二乗になっている部分を探す。二つ目、三つの項が、完全平方式になっていないかを、調べる。三つ目、マイナスでくくると、完全平方式が、現れることがある。", bx2)
    S.append(s)

    # ------------------------------------------------------------ pr17
    S.append(practice("練習17", ["(1) $x^2-y^2+6y-9$", "(2) $x^2-4x+4-9y^2$"], sec=45,
                      say_read="練習十七です。二問あります。平方の差を作れるか、考えてみましょう。",
                      say_think="制限時間は、四十五秒です。ヒントは、どの三つの項が、完全平方式になるか、です。"))

    s = Scene("練習17 の答え", "平方の差を作る")
    w1 = Work("(1) $x^2-y^2+6y-9$", size=48, lw=64)
    w2 = Work("(2) $x^2-4x+4-9y^2$", size=48, lw=64)
    s.beat("(1)。ワイを含む三つの項、マイナスワイの二乗、たす六ワイ、ひく九を、マイナスでくくります。ワイの二乗、ひく六ワイ、たす九になります。", w1.row(r"x^2-y^2+6y-9"), w1.row(r"x^2-(y^2-6y+9)"))
    s.beat("かっこの中は、ワイひく三の、二乗です。", w1.row(r"x^2-(y-3)^2"))
    s.beat("平方の差の形なので、エックスたす、かっこ、ワイひく三、かける、エックスひく、かっこ、ワイひく三。かっこをはずして、エックスたすワイひく三、かける、エックスひくワイたす三。", w1.row(r"(x+y-3)(x-y+3)", ans=True))
    s.beat("(2)。今度は、エックスを含む三つの項、エックスの二乗ひく四エックスたす四が、完全平方式です。エックスひく二の、二乗です。", w2.row(r"x^2-4x+4-9y^2"), w2.row(r"(x-2)^2-9y^2"))
    s.beat("九ワイの二乗は、三ワイの二乗です。平方の差の形になりました。", w2.row(r"(x-2)^2-(3y)^2"))
    s.beat("エックスひく二、たす三ワイ、かける、エックスひく二、ひく三ワイ。", w2.row(r"(x-2+3y)(x-2-3y)", ans=True))
    S.append(s)

    # ------------------------------------------------------------ ex6
    s = Scene("例題6", "$x^4-8x^2-9$")
    s.beat("例題六。次の式を、因数分解せよ。エックスの四乗、ひく八エックスの二乗、ひく九。", Prob("例題6", "$x^4-8x^2-9$"), voice="K")
    s.beat("エックスの四乗は、エックスの二乗の、二乗です。ですから、エックスの二乗を、ひとかたまりの文字として、見ることができます。", Eq(r"x^4=(x^2)^2", size=68))
    w = Work(size=54, lw=70)
    s.beat("式を書き換えます。エックスの二乗を、二乗して、ひく八エックスの二乗、ひく九。", w.row(r"x^4-8x^2-9"), w.row(r"(x^2)^2-8x^2-9", note="←$x^4=(x^2)^2$"))
    s.beat("ここで、エックスの二乗を、エーとおきます。すると、エーの二乗、ひく八エー、ひく九。かけて、マイナス九、足して、マイナス八になる、二つの数は、一と、マイナス九。エーたす一、かける、エーひく九、です。", w.row(r"(x^2+1)(x^2-9)", note="←$x^2=A$ とおくと\n$A^2-8A-9=(A+1)(A-9)$"))
    s.beat("まだ終わりではありません。エックスの二乗ひく九は、平方の差。エックスたす三、かける、エックスひく三、に、さらに因数分解できます。", w.row(r"(x^2+1)(x+3)(x-3)", ans=True))
    bx = Box("warn", T("因数分解は、[[r:これ以上できなくなるまで]]続ける。"), T("$x^2+1$ は、実数の範囲では、これ以上因数分解できない。"))
    s.beat("注意です。因数分解は、これ以上できなくなるまで、続けます。一方、エックスの二乗たす一は、実数の範囲では、これ以上、因数分解できません。ここで、完成です。", bx)
    S.append(s)

    # ------------------------------------------------------------ pr18
    S.append(practice("練習18", ["(1) $x^4-5x^2+4$", "(2) $x^4-81$", "(3) $(x^2+3x)^2-2(x^2+3x)-8$"], sec=60,
                      say_read="練習十八です。三問あります。置き換えを使えるか、考えてみましょう。",
                      say_think="制限時間は、六十秒です。三番は、かたまりに、注目してください。"))

    s = Scene("練習18 の答え (1)(2)", "置き換え・平方の差")
    w1 = Work("(1) $x^4-5x^2+4$", size=48, lw=64)
    w2 = Work("(2) $x^4-81$", size=48, lw=64)
    s.beat("(1)。エックスの二乗を、エーとおくと、エーの二乗、ひく五エー、たす四。かけて四、足してマイナス五は、マイナス一と、マイナス四。エーひく一、かける、エーひく四。", w1.row(r"x^4-5x^2+4"), w1.row(r"(x^2-1)(x^2-4)", note="←$A^2-5A+4=(A-1)(A-4)$"))
    s.beat("どちらのかっこも、平方の差です。さらに、因数分解します。エックスたす一、エックスひく一、エックスたす二、エックスひく二。", w1.row(r"(x+1)(x-1)(x+2)(x-2)", ans=True))
    s.beat("(2)。エックスの四乗ひく八十一は、エックスの二乗の二乗、ひく、九の二乗。平方の差です。", w2.row(r"x^4-81"), w2.row(r"(x^2)^2-9^2"))
    s.beat("エックスの二乗たす九、かける、エックスの二乗ひく九。後ろは、もう一度、平方の差です。エックスの二乗たす九は、これ以上、分解できません。", w2.row(r"(x^2+9)(x^2-9)"), w2.row(r"(x^2+9)(x+3)(x-3)", ans=True))
    S.append(s)

    s = Scene("練習18 (3) の答え", "かたまりに注目")
    w = Work("(3) $(x^2+3x)^2-2(x^2+3x)-8$", size=50, lw=64)
    s.beat("(3)。エックスの二乗たす三エックスが、二回出てきます。これをひとかたまりとして、エーとおきます。", w.row(r"(x^2+3x)^2-2(x^2+3x)-8"), w.row(r"A^2-2A-8", note="←$x^2+3x=A$ とおく"))
    s.beat("エーの二乗、ひく二エー、ひく八。かけて、マイナス八、足して、マイナス二になる数は、マイナス四と、二。エーひく四、かける、エーたす二。", w.row(r"(A-4)(A+2)"))
    s.beat("エーを、エックスの二乗たす三エックスに戻します。かっこの中は、エックスの二乗たす三エックスひく四と、エックスの二乗たす三エックスたす二。", w.row(r"(x^2+3x-4)(x^2+3x+2)"))
    s.beat("それぞれの、かっこが、さらに因数分解できます。エックスの二乗たす三エックスひく四は、エックスたす四、かける、エックスひく一。エックスの二乗たす三エックスたす二は、エックスたす一、かける、エックスたす二。", w.row(r"(x+4)(x-1)(x+1)(x+2)", ans=True))
    s.beat("置き換えたあとに、戻して終わりではなく、もう一度、分解できないかを、確認する。これが、大切なポイントです。", Box("point", T("置き換えて因数分解 → 元に戻す → [[o:もう一度、分解できないか確認]]")))
    S.append(s)

    S.append(summary("第2回のまとめ", ["式の一部を[[o:ひとかたまり]]の文字とみなすと、見通しがよくなる。",
                                      "平方の差 $X^2-Y^2$ の形を作れば、公式 $(X+Y)(X-Y)$ が使える。",
                                      "$x^4$ のような式は、$x^2=A$ と[[b:置き換え]]て考える。",
                                      "因数分解は、[[r:これ以上できなくなるまで]]続ける。"],
                     "第二回のまとめです。",
                     ["一つ目。式の一部を、ひとかたまりの文字とみなすと、見通しがよくなります。",
                      "二つ目。平方の差の形を作れば、和と差の積の公式が使えます。",
                      "三つ目。エックスの四乗のような式は、エックスの二乗を、エーと置き換えて、考えます。",
                      "四つ目。因数分解は、これ以上できなくなるまで、続けます。"],
                     closing="次回は、文字が複数ある式を、降べきの順に整理して、因数分解します。"))
    return S
