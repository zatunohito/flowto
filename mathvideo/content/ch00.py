             ("因数分解② 式の特徴に着目", "第二回は、式の特徴に着目する因数分解。置き換えと、平方の差を、見抜きます。"),
             ("因数分解③ 降べきの順", "第三回は、文字が複数ある式を、降べきの順に整理して、因数分解します。"),
             ("発展 3次式の展開と因数分解", "第四回は、発展。三次式の、展開と因数分解です。立方の公式を、図でも理解します。"),
