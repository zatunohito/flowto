from dsl import *
from lib import *

META = dict(chip="第1回", title="因数分解① たすき掛け", say="第一回、因数分解、その一、たすき掛け", color="#2563eb", bgm=["calm", "focus"])
PARTS = [('前編', None), ('後編', '例題4 (1)')]


def build():
    S = []
    S.append(opening("第1回", "因数分解① たすき掛け", "$ax^2+bx+c$ を因数分解する、王道のテクニック",
                     ["因数分解と展開の関係をいえる", "たすき掛けが「なぜ」うまくいくのか説明できる", "文字が2つの式にも、たすき掛けを使える"],
                     "第一回は、因数分解の中でも、いちばんよく使う、たすき掛けです。",
                     ["一つ目。因数分解と展開が、逆向きの計算であることを、確認します。",
                      "二つ目。たすき掛けが、どうしてうまくいくのか。仕組みから、理解します。",
                      "三つ目。エックスとワイのような、文字が二つの式にも、たすき掛けを使えるようになります。"]))

    # ---------------------------------------------------------------- S1
    s = Scene("因数分解とは？", "展開の逆向きの計算")
    cv, top, bot = LR("(x+2)(x+3)", "x^2+5x+6")
    s.beat("まず、おさらいです。かっこをはずして、一つの多項式にすることを、展開といいます。たとえば、エックスたす二、かける、エックスたす三、を展開すると、エックスの二乗、たす五エックス、たす六、になります。", cv, top)
    s.beat("反対に、エックスの二乗たす五エックスたす六を、かっこの、かけ算の形に直すことを、因数分解といいます。因数分解は、展開の、逆向きの計算なのです。", bot)
    b = Box("def", T("多項式を、いくつかの式の[[o:積]]の形に直すこと。かけ合わされている一つ一つの式を、[[b:因数]]という。"))
    s.beat("かけ合わされている、一つ一つの式を、因数といいます。この例では、エックスたす二と、エックスたす三が、因数です。", b)
    t = Box("tip", T("答えが合っているかは、[[o:展開して元の式に戻るか]]で確かめられる。"), title="検算")
    s.beat("因数分解が、正しいかどうかは、展開すれば、すぐに確かめられます。これを、検算といいます。習慣にしましょう。", t)
    S.append(s)

    # ---------------------------------------------------------------- S2
    s = Scene("基本公式を復習しよう", "因数分解の公式")
    f1 = frow("共通因数", "ma+mb=m(a+b)", "例 $3x^2+6x=3x(x+2)$")
    f2 = frow("和と積", "x^2+(a+b)x+ab=(x+a)(x+b)", "例 $x^2+5x+6=(x+2)(x+3)$")
    f3 = frow("完全平方", r"a^2\pm2ab+b^2=(a\pm b)^2", "例 $x^2+6x+9=(x+3)^2$")
    f4 = frow("平方の差", "a^2-b^2=(a+b)(a-b)", "例 $x^2-9=(x+3)(x-3)$")
    bx = Box("formula", f1, f2, f3, f4)
    s.beat("公式を四つだけ、おさらいします。一つ目は、共通因数。すべての項に共通する文字や数を、かっこの外にくくり出します。三エックスの二乗たす六エックスは、三エックスをくくり出して、三エックス、かっこ、エックスたす二、です。", f1, bx)
    s.beat("二つ目は、和と積の公式。エックスの二乗、たす、エーたすビー、エックス、たす、エービー、は、エックスたすエー、かける、エックスたすビー、になります。足して、エーたすビー、かけて、エービーになる、二つの数を探すのが、コツです。たとえば、エックスの二乗たす五エックスたす六は、足して五、かけて六になる、二と三を使って、エックスたす二、かける、エックスたす三、です。", f2)
    s.beat("三つ目は、完全平方式。エーの二乗、たす二エービー、たすビーの二乗は、エーたすビーの二乗。マイナスのときは、エーひくビーの二乗、です。", f3)
    s.beat("四つ目は、平方の差。エーの二乗ひくビーの二乗は、エーたすビー、かける、エーひくビー。二乗ひく二乗は、和と差の積、と覚えましょう。", f4)
    s.beat("ただし、これらの公式は、エックスの二乗の係数が、一のときに使いやすい形です。係数が一以外のときは、どうするか。そこで登場するのが、たすき掛けです。", T("$x^2$ の係数が $1$ でないときは…？　→　[[o:たすき掛け]]", "big c"), sfx="sparkle")
    S.append(s)

    # ---------------------------------------------------------------- S3 mechanism
    s = Scene("たすき掛けの仕組み", "なぜうまくいくのか")
    w = Work(size=62)
    s.beat("たすき掛けが、なぜうまくいくのか、仕組みから理解しましょう。ピーエックスたすキュー、かける、アールエックスたすエス、を、展開してみます。", w.row(r"(px+q)(rx+s)"))
    s.beat("分配法則で、四つの項ができます。ピーアール、エックスの二乗。ピーエス、エックス。キューアール、エックス。そして、キューエス。", w.row(r"pr\,x^2+ps\,x+qr\,x+qs"))
    s.beat("エックスの項を、まとめます。すると、エックスの二乗の係数は、ピーアール。エックスの係数は、ピーエス、たす、キューアール。定数項は、キューエス。この三つの形が、見えてきました。", w.row(r"\o{pr}\,x^2+(\bl{ps}+\pu{qr})\,x+\gr{qs}"))
    bx = Box("point",
             T("$x^2$ の係数 $=\\o{pr}$　（左の2数の積）"),
             T("定数項 $=\\gr{qs}$　（右の2数の積）"),
             T("$x$ の係数 $=\\bl{ps}+\\pu{qr}$　（斜めの積の和）"))
    s.beat("逆から読むと、こうなります。エックスの二乗の係数を、ピーとアールの積に分ける。定数項を、キューとエスの積に分ける。そして、斜めに掛けて足した、ピーエス、たす、キューアールが、エックスの係数に、なっていればよいのです。", bx)
    S.append(s)

    s = Scene("たすき掛けの図", "斜めに掛けて、足す")
    tk = Tasuki("p", "r", "q", "s", "qr", "ps", "pr", "qs", "ps+qr", cw=1.4, pw=3.2, size=70)
    side = Col(T("[[o:左の積]] $pr$ → $x^2$ の係数"), T("[[g:右の積]] $qs$ → 定数項"), T("[[b:斜めの和]] $ps+qr$ → $x$ の係数"), gap=10)
    rw = Row(tk, side, flex=[1.1, 1.3], align="center", gap=30)
    s.beat("図にしてみましょう。左側に、エックスの二乗の係数を作る、ピーとアールを、縦に並べます。", tk.part("left"))
    s.beat("右側に、定数項を作る、キューとエスを、縦に並べます。", tk.part("right"))
    s.beat("そして、斜めに掛け合わせます。ピーかけるエスと、アールかけるキュー。これが、たすき掛け、の名前の由来です。", tk.part("cross"), tk.part("prod"))
    s.beat("一番下の段を見てください。左は、ピーアールで、エックスの二乗の係数。右は、キューエスで、定数項。そして、斜めの積を足した、ピーエスたすキューアールが、エックスの係数です。この三つが、すべて元の式と一致すれば、因数分解できたことになります。", tk.part("total"), side)
    s.beat("答えは、上の段と下の段を、それぞれ読みます。上の段は、ピーエックスたすキュー。下の段は、アールエックスたすエス。この二つの積が、因数分解の結果です。", Eq(r"(px+q)(rx+s)", color="#2563eb"))
    S.append(s)

    # ---------------------------------------------------------------- S4 procedure
    s = Scene("たすき掛けの手順", "4ステップ")
    st = Steps()
    s.beat("では、手順をまとめましょう。", T("$ax^2+bx+c$ を因数分解する手順", "big"))
    s.beat("ステップ一。エックスの二乗の係数を、二つの数の積に分けて、左に縦に書きます。", st.item("$x^2$ の係数を2数の積に分けて、[[o:左]]に縦に書く"))
    s.beat("ステップ二。定数項を、二つの数の積に分けて、右に縦に書きます。", st.item("定数項を2数の積に分けて、[[g:右]]に縦に書く"))
    s.beat("ステップ三。斜めに掛けて足し、エックスの係数と、一致するかを確かめます。", st.item("斜めに掛けて足し、$x$ の係数と[[b:一致するか]]確かめる"))
    s.beat("ステップ四。一致しなければ、組み合わせや、符号、上下の順番を変えて、もう一度試します。一致したら、各段を読んで、かっこで書きます。", st.item("一致するまで、組み合わせ・符号・順番を変えて試す"))
    S.append(s)

    # ---------------------------------------------------------------- S5 easy example
    s = Scene("練習用の小さな例", "2x²+7x+3")
    ng = Tasuki.ints(2, 1, 3, 1, target=7)
    ok = Tasuki.ints(2, 1, 1, 3, target=7)
    for t_ in (ng, ok):
        t_.size = 56
    c1 = Col(T("右を $3$ と $1$ にすると…", "sm"), ng, gap=8)
    c2 = Col(T("上下を入れ替えて $1$ と $3$ にすると…", "sm"), ok, gap=8)
    res = Eq(r"2x^2+7x+3=(2x+1)(x+3)", size=56)
    s.beat("練習用に、小さな例で、動かしてみましょう。二エックスの二乗、たす七エックス、たす三、です。左は、二と一。定数項の三は、一と三に分けられます。", T("$2x^2+7x+3$ を因数分解しよう", "big c"))
    s.beat("まず、右の上下を、三と一にしてみます。斜めに掛けると、一かける三で三。二かける一で二。足して五。七ではありません。ざんねん、不一致です。", c1, ng.part("left"), ng.part("right"), ng.part("cross"), ng.part("prod"), ng.part("total"))
    s.beat("そこで、右の上下を、入れ替えて、一と三にします。一かける一で一。二かける三で六。足して七。ぴったりです。", c2, ok.part("left"), ok.part("right"), ok.part("cross"), ok.part("prod"), ok.part("total"))
    s.beat("上の段から、二エックスたす一。下の段から、エックスたす三。よって、二エックスの二乗たす七エックスたす三は、二エックスたす一、かける、エックスたす三、です。", res)
    S.append(s)

    # ---------------------------------------------------------------- S6 ex4(1)
    s = Scene("例題4 (1)", "$4x^2+8x-21$")
    s.beat("例題四の一。次の式を、因数分解せよ。四エックスの二乗、たす八エックス、ひく二十一。", Prob("例題4", "(1) $4x^2+8x-21$"), voice="K")
    cand = Box("point", T("$4=1\\times4$ ，または $2\\times2$"),
               T("$-21=(1,-21),\\ (-1,21),\\ (3,-7),\\ (-3,7)$ とその上下の入れ替え"), title="分け方の候補")
    s.beat("まず、候補を書き出します。四は、一かける四、または、二かける二。マイナス二十一は、一とマイナス二十一、マイナス一と二十一、三とマイナス七、マイナス三と七。それぞれ、上下を入れ替える場合も、あります。", cand)
    tr, refs = trio([("試し1", Tasuki.ints(1, 4, -3, 7, target=8), ""), ("試し2", Tasuki.ints(1, 4, 7, -3, target=8), ""),
                     ("試し3", Tasuki.ints(2, 2, -3, 7, target=8), "")], size=50)
    s.beat("全部を試すのは大変なので、順番に当たりをつけます。まず、左を一と四、右をマイナス三と七にします。斜めに掛けると、四かけるマイナス三で、マイナス十二。一かける七で、七。足して、マイナス五。八ではありません。", *[refs[0][0].part(k) for k in ("left", "right", "cross", "prod", "total")])
    s.beat("右の上下を、入れ替えてみます。四かける七で、二十八。一かけるマイナス三で、マイナス三。足して、二十五。これも違います。", *[refs[1][0].part(k) for k in ("left", "right", "cross", "prod", "total")])
    s.beat("次は、左を、二と二にします。右は、マイナス三と七。二かけるマイナス三で、マイナス六。二かける七で、十四。足して、八。ぴったりです。", *[refs[2][0].part(k) for k in ("left", "right", "cross", "prod", "total")])
    s.top.insert(0, tr) if tr not in s.top else None
    S.append(s)

    s = Scene("例題4 (1) の答え", "各段を読む")
    ok = Tasuki.ints(2, 2, -3, 7, target=8, size=64)
    w = Work()
    s.beat("成功した図を読みましょう。", ok.part("left"), ok.part("right"), ok.part("cross"), ok.part("prod"), ok.part("total"), sfx="ding")
    rows(s, w, [("上の段は、二エックスひく三。下の段は、二エックスたす七。", "4x^2+8x-21"),
                ("よって、四エックスの二乗たす八エックスひく二十一は、二エックスひく三、かける、二エックスたす七、と因数分解できます。", "(2x-3)(2x+7)", dict(ans=True)),
                ("念のため、検算です。展開すると、四エックスの二乗、たす十四エックス、ひく六エックス、ひく二十一。まとめて、四エックスの二乗たす八エックスひく二十一。元の式に戻りました。", r"4x^2+14x-6x-21=4x^2+8x-21", dict(lead="検算", text_lead=True, note="✔ 一致！"))])
    tipbox = Box("tip", T("定数項が[[r:マイナス]]なら、右の2数は[[o:符号が逆]]。まず足して中央になりそうな候補に絞ると、早く見つかる。"), title="コツ")
    s.beat("コツです。定数項がマイナスのときは、右の二つの数は、符号が逆になります。この性質を使って、候補を絞ると、早く見つかります。", tipbox)
    S.append(s)

    # ---------------------------------------------------------------- S7 ex4(2)
    s = Scene("例題4 (2)", "$4x^2-9xy+2y^2$")
    s.beat("例題四の二。次の式を、因数分解せよ。四エックスの二乗、ひく九エックスワイ、たす二ワイの二乗。", Prob("例題4", "(2) $4x^2-9xy+2y^2$"), voice="K")
    s.beat("文字が二つあっても、考え方は同じです。ワイを、ただの数のように見て、エックスの、二次式として、たすき掛けをします。ワイの二乗の係数は、定数項の役目です。", T("$y$ を「数」と思って、$x$ の2次式として考える", "big c"))
    tk = Tasuki.ints(1, 4, -2, -1, var="y", target=-9, size=64)
    s.beat("左は、一と四。右は、定数項の二ワイの二乗を、マイナス二ワイと、マイナスワイに分けます。四かけるマイナス二ワイで、マイナス八ワイ。一かけるマイナスワイで、マイナスワイ。足して、マイナス九ワイ。エックスの係数と、一致します。",
           tk.part("left"), tk.part("right"), tk.part("cross"), tk.part("prod"), tk.part("total"))
    w = Work()
    rows(s, w, [("上の段は、エックスひく二ワイ。下の段は、四エックスひくワイ。", "4x^2-9xy+2y^2"),
                ("したがって、エックスひく二ワイ、かける、四エックスひくワイ、です。", "(x-2y)(4x-y)", dict(ans=True)),
                ("検算。展開して、四エックスの二乗、ひくエックスワイ、ひく八エックスワイ、たす二ワイの二乗。確かに、元の式です。", r"4x^2-xy-8xy+2y^2=4x^2-9xy+2y^2", dict(lead="検算", text_lead=True))])
    S.append(s)

    # ---------------------------------------------------------------- S8 practice 16
    S.append(practice("練習16", ["(1) $2x^2+3x+1$", "(2) $4x^2-15x+9$", "(3) $6x^2-5x-6$", "(4) $3x^2-2xy-y^2$", "(5) $3a^2-14ab+8b^2$", "(6) $4x^2+7ax-2a^2$"],
                      cols=2, sec=60, say_read="練習十六です。六問あります。たすき掛けを使って、解いてみましょう。",
                      say_think="制限時間は、六十秒です。紙に書いて、解いてみてください。"))

    items1 = [("(1) $2x^2+3x+1$", Tasuki.ints(1, 2, 1, 1, target=3), r"(x+1)(2x+1)"),
              ("(2) $4x^2-15x+9$", Tasuki.ints(1, 4, -3, -3, target=-15), r"(x-3)(4x-3)"),
              ("(3) $6x^2-5x-6$", Tasuki.ints(2, 3, -3, 2, target=-5), r"(2x-3)(3x+2)")]
    s = Scene("練習16 の答え (1)〜(3)", "たすき掛けで確認")
    tr, refs = trio(items1, size=50)
    says = [("(1)。二エックスの二乗は、一と二。定数項の一は、一と一。斜めに、二かける一で二。一かける一で一。足して三。一致です。上の段が、エックスたす一。下の段が、二エックスたす一。", "(1)の答え。エックスたす一、かける、二エックスたす一。"),
            ("(2)。四は、一と四。九は、マイナス三と、マイナス三。定数項が正で、中央がマイナスなので、右はどちらもマイナスです。四かけるマイナス三で、マイナス十二。一かけるマイナス三で、マイナス三。足して、マイナス十五。一致です。", "(2)の答え。エックスひく三、かける、四エックスひく三。"),
            ("(3)。六は、二と三。マイナス六は、マイナス三と二。三かけるマイナス三で、マイナス九。二かける二で、四。足して、マイナス五。一致です。", "(3)の答え。二エックスひく三、かける、三エックスたす二。")]
    for (a, b), (tk_, eq_) in zip(says, refs):
        s.beat(a, *[tk_.part(k) for k in ("left", "right", "cross", "prod", "total")])
        s.beat(b, eq_, sfx="chime")
    S.append(s)

    items2 = [("(4) $3x^2-2xy-y^2$", Tasuki.ints(1, 3, -1, 1, var="y", target=-2), r"(x-y)(3x+y)"),
              ("(5) $3a^2-14ab+8b^2$", Tasuki.ints(1, 3, -4, -2, var="b", target=-14), r"(a-4b)(3a-2b)"),
              ("(6) $4x^2+7ax-2a^2$", Tasuki.ints(1, 4, 2, -1, var="a", target=7), r"(x+2a)(4x-a)")]
    s = Scene("練習16 の答え (4)〜(6)", "文字が2つの式")
    tr, refs = trio(items2, size=50)
    says = [("(4)。三エックスの二乗の三は、一と三。マイナスワイの二乗は、マイナスワイと、ワイ。三かけるマイナスワイで、マイナス三ワイ。一かけるワイで、ワイ。足して、マイナス二ワイ。一致です。", "(4)の答え。エックスひくワイ、かける、三エックスたすワイ。"),
            ("(5)。エーの二乗の係数三は、一と三。八ビーの二乗は、マイナス四ビーと、マイナス二ビー。三かけるマイナス四ビーで、マイナス十二ビー。一かけるマイナス二ビーで、マイナス二ビー。足して、マイナス十四ビー。一致です。", "(5)の答え。エーひく四ビー、かける、三エーひく二ビー。"),
            ("(6)。四は、一と四。マイナス二エーの二乗は、二エーと、マイナスエー。四かける二エーで、八エー。一かけるマイナスエーで、マイナスエー。足して、七エー。一致です。", "(6)の答え。エックスたす二エー、かける、四エックスひくエー。")]
    for (a, b), (tk_, eq_) in zip(says, refs):
        s.beat(a, *[tk_.part(k) for k in ("left", "right", "cross", "prod", "total")])
        s.beat(b, eq_, sfx="chime")
    S.append(s)

    S.append(summary("第1回のまとめ", ["因数分解は、展開の[[o:逆向き]]。答えは展開して検算する。",
                                      "たすき掛け：左の積＝$x^2$の係数、右の積＝定数項、[[b:斜めの積の和]]＝$x$の係数。",
                                      "一致しないときは、[[o:順番・符号・組み合わせ]]を変えて試す。",
                                      "文字が2つの式でも同じ。片方の文字を[[g:数のように]]見て、たすき掛け。"],
                     "第一回のまとめです。",
                     ["一つ目。因数分解は、展開の逆向き。答えは、展開して検算します。",
                      "二つ目。たすき掛けでは、左の積が、エックスの二乗の係数。右の積が、定数項。斜めの積の和が、エックスの係数です。",
                      "三つ目。一致しないときは、順番や、符号や、組み合わせを変えて、試します。",
                      "四つ目。文字が二つの式でも、同じです。片方の文字を、数のように見て、たすき掛けをします。"],
                     closing="次回は、式の特徴に着目して、因数分解の公式を使う、工夫を学びます。"))
    return S
